"""J5: scroll wheel (work part wheel)."""
import os, sys, math, traceback
sys.path.insert(0, r"C:\NX_MCP_WORKSPACE\mouse_pcb_nx\nx")
from common import *  # noqa
L = Log("j5_wheel")
try:
    assy, comp, wp, ctrl, pcbc = start("wheel")
    interp_safe(wp, ["whl_d", "whl_w", "ax_y", "ax_z"])
    X = lambda n, f, c="": xset(wp, n, f, "mm", c)
    X("hub_l_d", "6", "left hub")
    X("hub_l_len", "3.4", "left hub length (ends 0.49 before the encoder shaft end x=-7.39)")
    X("stub_d", "3.4", "encoder stub (EC10E hollow shaft bore 3.6 in the STEP placeholder)")
    X("stub_len", "5.1", "stub length; 4.6 engages the shaft")
    X("stub_flat", "1.35", "D-flat distance from the axis")
    X("hub_r_d", "5", "right hub")
    X("hub_r_len", "0.7", "")
    X("pin_bore", "1.95", "press bore for the 2 mm steel axle pin")
    X("pin_depth", "4.5", "press depth of the axle pin (opens on the flat right face = print bed side)")
    X("groove_w", "1.0", "grip groove width")
    X("groove_h", "0.6", "grip groove depth")
    xset(wp, "n_groove", "24", None, "grip grooves")
    X("rim_r", "0.8", "rim edge blend")
    nxh.update()
    f, W = cyl(wp, ("-whl_w/2", "ax_y", "ax_z"), (1.0, 0.0, 0.0), "whl_d", "whl_w", name="WHEEL_RIM")
    v0 = nxh.volume(wp, W)
    L.check("rim volume = pi r2 w", abs(v0 - math.pi * 11 ** 2 * 7) < 1e-3, v0)
    rep = nxf.blend_chains(wp, [lambda: [e for e in W.GetEdges() if e.SolidEdgeType == NXOpen.Edge.EdgeType.Circular]], "rim_r")
    L.note("rim blend", rep)
    cyl(wp, ("-whl_w/2-hub_l_len", "ax_y", "ax_z"), (1.0, 0.0, 0.0), "hub_l_d", "hub_l_len", op=BOOL.Unite, target=W, name="HUB_L")
    cyl(wp, ("-whl_w/2-hub_l_len-stub_len", "ax_y", "ax_z"), (1.0, 0.0, 0.0), "stub_d", "stub_len", op=BOOL.Unite, target=W, name="ENC_STUB")
    cyl(wp, ("whl_w/2-pin_depth", "ax_y", "ax_z"), (1.0, 0.0, 0.0), "pin_bore", "pin_depth", op=BOOL.Subtract, target=W, name="PIN_BORE")
    fd, D, st = rect_prism(wp, "-whl_w/2-hub_l_len-stub_len/2", "ax_y", "stub_len+0.2", "stub_d+1", "ax_z+stub_flat", "ax_z+stub_d", "D_FLAT")
    nxh.subtract(wp, W, [D])
    v0g = nxh.volume(wp, W)
    fg, _, st = rect_prism(wp, "0", "ax_y", "whl_w+2", "groove_w", "ax_z+whl_d/2-groove_h", "ax_z+whl_d/2+1", "GROOVE", op=BOOL.Subtract, target=W)
    v1 = nxh.volume(wp, W)
    L.check("one groove removed", v1 < v0g, [v0g, v1])
    pat = nxf.pattern_circular(wp, [fg], (0.0, E(wp, "ax_y"), E(wp, "ax_z")), (1.0, 0.0, 0.0), "n_groove")
    v2 = nxh.volume(wp, W)
    L.note("groove pattern", v1, v2)
    L.check("grooves patterned (23 more grooves, ~same volume each)", abs((v1 - v2) - 23 * (v0g - v1)) < 0.05 * 23 * (v0g - v1), [v0g, v1, v2])
    W.SetName("WHEEL")
    color(W, 216)
    sol = product(wp)
    L.check("wheel one solid", len(sol) == 1, [b.Name for b in sol])
    bb = exact_bbox(W)
    L.check("wheel x span -12.0..3.5", abs(bb[0] + 12.0) < 0.02 and abs(bb[3] - 3.5) < 0.02, bb)
    errs = nxh.feature_errors(wp)
    L.check("no feature errors", not errs, errs)
    save_only(wp)
    L.finish(True)
except Exception:
    L.res["error"] = traceback.format_exc(); L.flush()
