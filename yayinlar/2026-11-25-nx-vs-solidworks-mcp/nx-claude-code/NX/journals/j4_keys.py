"""J4: separate keys - btn_left, btn_right (flexure tongue + M2 screw), key_fwd, key_back (side keys on a
1.75 mm filament hinge pin). One NX process, one work part after the other."""
import os, sys, traceback
sys.path.insert(0, r"C:\NX_MCP_WORKSPACE\mouse_pcb_nx\nx")
from common import *  # noqa
L = Log("j4_keys")
NAMES = ["z_pl", "nub_gap", "nub_d", "pl12_x", "pl12_y", "pl56_x", "pl5_y", "pl6_y", "tg_x", "tg_y", "tg_y0", "tg_w",
         "tg_z", "tg_t", "btn_ry", "clr_d", "pin_x", "pin_z", "pin_hole", "arm_x1", "arm_z1", "sk_x", "lug_hw", "lug_z0"]
try:
    assy = open_design()
    ctrl = comp_by_leaf(assy, "mouse_ctrl")

    def main_button(key, sg, tool):
        comp = comp_by_leaf(assy, key)
        wp = nxa.set_work(comp)
        reset_part(wp)
        interp_safe(wp, NAMES)
        nxh.update()
        fH, H = link_body_by_name(wp, ctrl, "HOUSING")
        fE, ENV = link_body_by_name(wp, ctrl, "ENVELOPE")
        fT, T = link_body_by_name(wp, ctrl, tool)
        nxh.intersect(wp, H, [T])
        L.check(key + " skin patch", H.IsSolidBody, nxh.volume(wp, H))
        fb, N = cyl(wp, (sg + "pl12_x", "pl12_y", "z_pl+nub_gap"), (0.0, 0.0, 1.0), "nub_d", "30", name="NUB")
        env_cut(wp, N, ENV)
        nxh.unite(wp, H, [N])
        fr, R, st = rect_prism(wp, sg + "tg_x", "btn_ry+1.0", "tg_w", "2.0", "tg_z", "40", "RISER")
        env_cut(wp, R, ENV)
        nxh.unite(wp, H, [R])
        ft, TG, st = rect_prism(wp, sg + "tg_x", "(tg_y0+btn_ry+2.0)/2", "tg_w", "btn_ry+2.0-tg_y0", "tg_z", "tg_z+tg_t", "TONGUE")
        nxh.unite(wp, H, [TG])
        cyl(wp, (sg + "tg_x", "tg_y", "tg_z-1"), (0.0, 0.0, 1.0), "clr_d", "tg_t+2", op=BOOL.Subtract, target=H, name="M2_CLEAR")
        H.SetName(key.upper())
        color(H, 6)
        sol = product(wp)
        L.check(key + " one solid", len(sol) == 1, [b.Name for b in sol])
        L.check(key + " nub tip at z_pl+nub_gap", nxh.dist_to(wp, H, (float(sg + "1") * E(wp, "pl12_x"), E(wp, "pl12_y"), E(wp, "z_pl") + E(wp, "nub_gap"))) < 1e-3, None)
        errs = nxh.feature_errors(wp)
        L.check(key + " no feature errors", not errs, errs)
        L.note(key, "volume", nxh.volume(wp, H), "bbox", exact_bbox(H))
        L.check(key + " product body in MODEL", to_model(wp, H), None)
        save_only(wp)

    def side_key(key, tool, yc):
        comp = comp_by_leaf(assy, key)
        wp = nxa.set_work(comp)
        reset_part(wp)
        interp_safe(wp, NAMES)
        nxh.update()
        fH, H = link_body_by_name(wp, ctrl, "HOUSING")
        fE, ENV = link_body_by_name(wp, ctrl, "ENVELOPE")
        fT, T = link_body_by_name(wp, ctrl, tool)
        nxh.intersect(wp, H, [T])
        L.check(key + " pad", H.IsSolidBody, nxh.volume(wp, H))
        fa, A, st = rect_prism(wp, "(sk_x-4+arm_x1)/2", yc, "arm_x1-sk_x+4", "3.5", "z_pl+nub_gap", "arm_z1", "ARM")
        env_cut(wp, A, ENV)
        nxh.unite(wp, H, [A])
        fl, LG, st = rect_prism(wp, "pin_x", yc, "2*lug_hw", "3.0", "lug_z0", "z_pl+nub_gap+0.3", "LUG")
        nxh.unite(wp, H, [LG])
        cyl(wp, ("pin_x", yc + "-3", "pin_z"), (0.0, 1.0, 0.0), "pin_hole", "6", op=BOOL.Subtract, target=H, name="PIN_HOLE")
        H.SetName(key.upper())
        color(H, 6)
        sol = product(wp)
        L.check(key + " one solid", len(sol) == 1, [b.Name for b in sol])
        L.check(key + " arm underside at z_pl+nub_gap over the plunger",
                nxh.dist_to(wp, H, (E(wp, "pl56_x"), E(wp, yc), E(wp, "z_pl") + E(wp, "nub_gap"))) < 1e-3, None)
        errs = nxh.feature_errors(wp)
        L.check(key + " no feature errors", not errs, errs)
        L.note(key, "volume", nxh.volume(wp, H), "bbox", exact_bbox(H))
        L.check(key + " product body in MODEL", to_model(wp, H), None)
        save_only(wp)

    main_button("btn_left", "-", "T_BTN_L")
    main_button("btn_right", "", "T_BTN_R")
    side_key("key_fwd", "T_SKF", "pl5_y")
    side_key("key_back", "T_SKB", "pl6_y")
    L.finish(True)
except Exception:
    L.res["error"] = traceback.format_exc(); L.flush()
